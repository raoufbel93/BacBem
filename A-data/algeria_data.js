// Helper function to get all wilayas as an array
function getWilayas() {
    return Object.entries(ALGERIA_DATA).map(([code, data]) => ({
        code,
        name: data.name
    }));
}

// Helper function to get municipalities for a specific wilaya
function getMunicipalities(wilayaCode) {
    const wilaya = ALGERIA_DATA[wilayaCode];
    return wilaya ? wilaya.municipalities : [];
}

